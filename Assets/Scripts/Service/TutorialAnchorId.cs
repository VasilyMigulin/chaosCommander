namespace Game.Core.Service
{
    // === enum ===
    /// <summary>
    /// Цели подсветки туториала. Вешаются компонентом TutorialAnchor на СТАТИЧНЫЕ элементы боевого UI;
    /// режиссёр (TutorialDirectorSystem) просит подсветить нужный id, оверлей (TutorialHighlightView)
    /// вырезает вокруг него дырку в затемнении.
    ///
    /// Динамику (конкретную карту в руке, конкретную клетку) НЕ адресуем поштучно — подсвечиваем ОБЛАСТЬ
    /// (рука / своя линия / сторона врага). Этого хватает, чтобы направить взгляд, и не требует
    /// регистрировать каждую карту.
    /// </summary>
    public enum TutorialAnchorId
    {
        None = 0,
        Commander,     // слот командира
        Gold,          // счётчик золота
        Mana,          // счётчик маны
        Hand,          // рука игрока
        OwnLine,       // своя передняя линия (куда призывают)
        EnemySide,     // сторона противника (существа + аватар)
        EndTurn,       // кнопка «Завершить ход»
    }
}
