namespace Game.Core.Shared.Interface
{
    /// <summary>Как выбирается цель у Target-способности. Значения ЗАКРЕПЛЕНЫ (ассеты хранят число —
    /// перестановка/вставка без явного значения ломает заавторенные карты, см. грабли CountSource).</summary>
    public enum TargetSelection
    {
        Random = 0,         // система берёт случайные из валидных
        Selected = 1,       // игрок выбирает кликом (async, через UI)
        Strongest = 2,      // система берёт Count с наибольшей атакой (Всадник Смерти). Синк через target-ключи (как Random).
        TriggerSubject = 3, // цель = ВИНОВНИК триггера (OnCreatureInvoked → вышедшее существо; «Неудачная молитва»).
                            // Фильтры применяются к нему: не прошёл → способность фуззлится. Count игнорируется.
        MostExpensive  = 4, // Count с наибольшей эффективной стоимостью. Имена как у DeckSummonPick (консистентно).
        LeastExpensive = 5, // Count с наименьшей стоимостью (Канализационный прорыв: «самое слабое существо» =
                            // дешевейшее). Синк через target-ключи (как Random/Strongest).
        MostWounded = 6,    // Count с наибольшим ПОТЕРЯННЫМ здоровьем (Домашний медик: «самому раненому»).
                            // Небитые (Current==Max) НЕ кандидаты — «раненому» без раненых = фузл.
                            // Синк через target-ключи (как Random/Strongest).
        TriggerSubjectAllowDead = 7,   // как TriggerSubject, но НЕ фуззлится, если виновник уже мёртв/снят с
                            // поля (Собиратель кукол: «когда существо умирает, призовите его копию» — сам
                            // виновник ЭТОЙ смерти к моменту резолва). Обычный TriggerSubject тут не годится:
                            // его гейт «жив ли субъект» — это Board-запрос с Exc<DeadTag>, а виновник уже
                            // помечен DeadTag. Фильтры по-прежнему применяются (FiltersOk), просто без
                            // требования быть в живом Board-списке. Count игнорируется, как у TriggerSubject.
    }

    /// <summary>Область действия Field-способности.</summary>
    public enum FieldArea
    {
        All,    // всё поле (обе стороны)
        Own,    // сторона игрока-кастера
        Enemy,  // сторона оппонента
    }

    /// <summary>Зона, из которой берутся кандидаты-цели. По умолчанию Board (существа на поле + игроки).
    /// Для не-Board зон (колода/рука/кладбище) Selected идёт через окно выбора, а не клики по клеткам.</summary>
    /// ЗНАЧЕНИЯ ЗАКРЕПЛЕНЫ ЯВНО: enum сериализуется в ассетах карт (AbilityToTarget.Zone), и перестановка
    /// членов молча поменяла бы зону у всех уже за-авторенных способностей — ровно тот класс багов, что уже
    /// случался с CountSource. Новые зоны добавлять ТОЛЬКО в конец, с новым числом.
    public enum TargetZone
    {
        Board = 0,   // существа на поле + игроки
        Deck  = 1,   // карты в колоде
        Hand  = 2,   // карты в руке
        Grave = 3,   // карты в кладбище
        Any   = 4,   // ВСЕ зоны сразу (борд+рука+колода+кладбище). Прежде всего для TargetSelection.TriggerSubject:
                     // виновник мог уехать куда угодно к моменту резолва (существо — на столе, заклинание — уже
                     // в кладбище), а зона его нахождения для реакции не важна — важны только его свойства (фильтры).

        /// <summary>«Отложенные» карты (сайдборд Сказочника): своя зона, ВНЕ колоды и руки. В Any НЕ входит —
        /// иначе любая способность «возьми что-нибудь откуда угодно» тянула бы карты из сайдборда, который
        /// по смыслу доступен только своей карте-носителю.</summary>
        Sideboard = 5,
    }

    /// <summary>Из какой зоны (зон) КАРТА-НОСИТЕЛЬ триггера может сработать — НЕ путать с TargetZone (та про
    /// зону КАНДИДАТОВ на цель способности, это про зону САМОГО источника триггера: «Распорядитель королевской
    /// тусовки» призывает Пока в руке, «Медлительный дворецкий» реагирует даже из руки/колоды/кладбища).
    /// Flags — можно сочетать несколько зон разом. ЗНАЧЕНИЯ ЗАКРЕПЛЕНЫ ЯВНО (степени двойки), как у
    /// TargetZone/CountSource — перестановка/вставка без явного числа молча сломает уже заавторенные карты.
    /// Новые зоны — ТОЛЬКО следующим свободным битом, в конец.</summary>
    [System.Flags]
    public enum TriggerZoneMask
    {
        None      = 0,
        Board     = 1 << 0,   // 1  — стол (умолчание почти всех триггеров — «как сейчас»)
        Hand      = 1 << 1,   // 2  — рука
        Deck      = 1 << 2,   // 4  — колода
        Grave     = 1 << 3,   // 8  — кладбище
        Sideboard = 1 << 4,   // 16 — сайдборд (см. TargetZone.Sideboard)
        Any       = Board | Hand | Deck | Grave | Sideboard,
    }
}
