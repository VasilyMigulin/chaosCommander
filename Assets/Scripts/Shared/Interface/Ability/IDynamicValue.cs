using Leopotam.EcsLite;

namespace Game.Core.Shared.Interface
{
    /// <summary>
    /// Эффект, чьё числовое значение подставляется в описание карты на месте токена *N*.
    /// Форматтер описания (CardDescriptionFormatter) проходит способности карты по порядку,
    /// собирает значения всех IDynamicValue-эффектов в плоский список и подставляет i-й
    /// токен *N* i-м значением. Вне боя (world == null) форматтер берёт фоллбэк прямо из
    /// текста (само число между звёздочками), поэтому реализация может опираться на world.
    ///
    /// Инвариант: GetDynamicValue ДОЛЖЕН читать ту же величину (с теми же модификаторами),
    /// что эффект применяет в Apply — тогда описание всегда совпадает с реальным эффектом
    /// (напр. «все заклинания +1 урона» отразится и в тексте, и в уроне).
    ///
    /// DynamicValueCount > 1 для эффектов с несколькими числами (BuffStats: ATK, потом HP) —
    /// порядок слотов должен совпадать с порядком токенов *N* в тексте.
    /// </summary>
    public interface IDynamicValue
    {
        /// <summary>Сколько чисел этот эффект выставляет в описание (обычно 1).</summary>
        int DynamicValueCount { get; }

        /// <summary>
        /// Значение слота index (0..DynamicValueCount-1) для показа в описании.
        /// world может быть null/невалиден вне боя — тогда верни авторское значение поля.
        /// </summary>
        int GetDynamicValue(int index, EcsWorld world, int cardEntity, int playerEntity);
    }
}
