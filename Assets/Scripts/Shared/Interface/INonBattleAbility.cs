using System;

namespace Game.Core.Shared.Interface
{
    // ─────────────────────────────────────────────────────────────────────────
    // НЕБОЕВЫЕ СПОСОБНОСТИ — отдельное семейство от Game.Core.Ability.
    //
    // ЗАЧЕМ ОТДЕЛЬНОЕ СЕМЕЙСТВО, а не ещё один ITrigger: боевая способность живёт в ECS-мире (сущность,
    // шина событий, очередь резолва, синк действий) и по определению требует, чтобы бой ШЁЛ. А эффекты
    // вроде «Босс качалки Билли» (стартовая рука 4) и «Сказочник» (отложить 3 карты при сборке колоды)
    // срабатывают ТАМ, ГДЕ ECS-мира ещё нет вовсе — в конструкторе колоды и в раздаче до первого хода.
    // Билли поэтому и был захардкожен двумя полями прямо в CardModel: приткнуть его было некуда.
    //
    // КОНТРАКТ: небоевая способность НИЧЕГО НЕ ДЕЛАЕТ — она ВНОСИТ ВКЛАД в агрегат правил. Все карты
    // колоды опрашиваются, вклады складываются по правилам, записанным в самом агрегате (напр. «рука =
    // максимум из требований»), и только потом кто-то один применяет результат. Отсюда:
    //   • две карты с одной механикой складываются предсказуемо, без «кто последний, тот и прав»;
    //   • порядок опроса не влияет на исход (важно для синка: оба клиента считают одно и то же);
    //   • правило разрешения конфликта лежит В ОДНОМ месте (агрегат), а не размазано по способностям.
    //
    // Реализации — [SerializeReference] в CardModel.NonBattleAbilities (как Archetypes/RuntimeAbilities).
    // Интерфейсы живут в Shared.Interface, потому что читать их обязаны ОБА мира: Game.Core.DeckBuilder
    // (сборка колоды, ECS не знает) и ECS-системы матча.
    // ─────────────────────────────────────────────────────────────────────────

    /// <summary>Небоевая способность карты. Маркер семейства; работу задают фазовые интерфейсы ниже.</summary>
    public interface INonBattleAbility
    {
        /// <summary>Человекочитаемое имя для инспектора/логов («Стартовая рука», «Сайдборд»).</summary>
        string DebugName { get; }
    }

    /// <summary>ФАЗА «сборка колоды»: меняет правила конструктора (доп. зоны, лимиты, требования).
    /// Опрашивается редактором колод и валидацией — до всякого боя.</summary>
    public interface IDeckBuildAbility : INonBattleAbility
    {
        void Contribute(ref DeckBuildRules rules);
    }

    /// <summary>ФАЗА «подготовка матча»: раздача и мулиган, ДО первого хода. Опрашивается на ините матча.</summary>
    public interface IMatchSetupAbility : INonBattleAbility
    {
        void Contribute(ref MatchSetupRules rules);
    }

    // ── Агрегаты правил ──────────────────────────────────────────────────────

    /// <summary>Правила сборки колоды, собранные со всех карт колоды (включая командира).</summary>
    [Serializable]
    public struct DeckBuildRules
    {
        /// <summary>Размер «отложенной» зоны (сайдборд): сколько карт игрок кладёт в сторону при сборке.
        /// 0 = зоны нет. Сказочник требует 3.</summary>
        public int SideboardSize;

        /// <summary>Требование сайдборда. МАКСИМУМ, а не сумма: две копии механики не удваивают зону —
        /// иначе две легендарки с сайдбордом молча превращали бы колоду в другую игру.</summary>
        public void RequireSideboard(int size)
        {
            if (size > SideboardSize) SideboardSize = size;
        }

        public bool HasSideboard => SideboardSize > 0;
    }

    /// <summary>Правила подготовки матча, собранные со всех карт колоды (включая командира).</summary>
    [Serializable]
    public struct MatchSetupRules
    {
        /// <summary>Абсолютный размер стартовой руки. 0 = не переопределён (берётся базовый по стороне).</summary>
        public int StartingHand;

        /// <summary>Разрешена замена любого числа предложенных карт.</summary>
        public bool UnlimitedReplace;

        /// <summary>Стартовая рука = МАКСИМУМ из требований (а не сумма): две карты «начинаете с 4»
        /// не должны давать 8. Базовый размер по стороне применяется отдельно и тоже участвует в максимуме.</summary>
        public void RaiseStartingHand(int size)
        {
            if (size > StartingHand) StartingHand = size;
        }

        /// <summary>Разрешение «менять сколько угодно» — липкое: достаточно одной карты.</summary>
        public void AllowUnlimitedReplace() => UnlimitedReplace = true;
    }
}
