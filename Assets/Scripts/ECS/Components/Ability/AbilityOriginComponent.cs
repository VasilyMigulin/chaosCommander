namespace Game.Core.Ecs.Components
{
    /// <summary>
    /// «Инициатор» способности — игрок, чей эффект ПОРОДИЛ эту способность, даже если она теперь висит на
    /// чужой сущности. Ставится AddAbilityEffect при гранте (Газовое вздутие вешает предсмертный
    /// ShuffleCardIntoDeck на существ ОППОНЕНТА → способность принадлежит оппоненту, но инициатор — ты).
    /// Нужно для корректной АТРИБУЦИИ генерации: «замешано вами» считается по инициатору, а не по владельцу
    /// карты-источника. Без компонента способность считается «своей» у владельца (нативные способности).
    /// СИНК: AddAbilityEffect выполняется на обоих клиентах (резолв реплеится) → компонент зеркален.
    /// </summary>
    public struct AbilityOriginComponent
    {
        public int OriginOwnerId;   // PlayerId инициатора
    }
}
