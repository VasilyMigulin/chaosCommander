namespace Game.Core.Ecs.Components
{
    // === struct (Component) ===
    /// <summary>
    /// ЛИМИТ АКТИВАЦИЙ способности ЗА ХОД (баланс-гейт, требование юзера 2026-07-30 после «Блаженного
    /// дьякона»: он генерировал ресурсы нон-стоп). Вешается на ABILITY-сущность в Ability.Init, если у
    /// способности задан Ability.MaxActivationsPerTurn > 0; 0 = БЕЗЛИМИТ (умолчание — старые ассеты без
    /// поля десериализуются в 0 и работают как раньше).
    ///
    /// Считаем ФАКТИЧЕСКИЕ применения (RunResolveAbilityQueueSystem инкрементит, когда эффекты реально
    /// применились), а не срабатывания триггера: холостой файр (фильтры не пропустили виновника — у
    /// дьякона это вторая, «не-жёлтая» способность при розыгрыше жёлтой карты) лимит НЕ съедает.
    /// Гейт стоит в AbilityFire.Mark — исчерпанная способность просто не запускается.
    /// Сброс — в начале хода ВЛАДЕЛЬЦА (RunTurnStartSystem по AbilityOwnerComponent.PlayerEntity).
    /// СИНК: гейт применяется у актива (он симулирует триггеры), пассив реплеит его решения снапшотами.
    /// </summary>
    public struct AbilityUseLimitComponent
    {
        public int Max;            // сколько раз за ход способность может ПРИМЕНИТЬСЯ
        public int UsedThisTurn;

        /// <summary>ОБЩИЙ счётчик для нескольких способностей ОДНОЙ карты (Ability.LimitGroup > 0):
        /// «под капотом две ветки — для игрока одна способность» («Блаженный дьякон»: жёлтая → копия,
        /// иначе → добор; вместе не больше раза за ход). 0 = индивидуальный лимит этой способности.
        /// Расход заряда разносится по всем способностям карты с тем же номером группы (см. резолв).</summary>
        public int Group;
    }
}
