namespace Game.Core.Ecs.Components
{
    // === struct (Component) ===
    /// <summary>
    /// «ЗАПИСКА О ПРИЧИНЕ»: карта появилась/разыгралась как СЛЕДСТВИЕ вот этой активации. Её собственные
    /// способности встанут в очередь детьми записанного узла, а не корнем (см. ActivationKey).
    ///
    /// ПОЧЕМУ КЛЮЧ, А НЕ ФЛАЖОК. Сначала тут был просто признак «разыграно эффектом», а родителя брали из
    /// глобального «кто резолвился последним». Каскад Королевской пиньяты это сломал: её хрип создаёт
    /// 10 карт разом, а разыгрываются они по одной с пейсингом — к моменту каста первой очередь давно
    /// опустела, глобальная причина стёрлась, и все 10 заклинаний получили корневые ключи (лог 2026-08-02:
    /// key=(69682,0,0), (69697,0,0), … вместо детей (69450,28,2)). Записка едет С КАРТОЙ, поэтому пауза
    /// между созданием и розыгрышем больше ничего не значит.
    ///
    /// Узел выделяется В МОМЕНТ порождения (TryNextReactionKey), поэтому 10 карт от одной причины получают
    /// разные номера и сохраняют порядок появления. Способности карты дальше делятся по AbilityIndex.
    ///
    /// Живёт до начала следующего хода: каскад не пересекает границу хода, а держать записку дольше значило
    /// бы, что карта, пролежавшая в руке до другого хода, утащит за собой древнюю волну.
    /// </summary>
    public struct CausedByActivationComponent
    {
        /// <summary>Узел ЭТОЙ карты в дереве причинности (уже потомок своей причины).</summary>
        public ActivationKey Node;
    }
}
